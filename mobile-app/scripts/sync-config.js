#!/usr/bin/env node
"use strict";

/**
 * Syncs mobile-app/app-config.json into:
 *   1. mobile-app/www/logo.jpg        (copied from images/LOGO.JPG)
 *   2. mobile-app/www/app-config.js   (read by the app boot & offline shell)
 *   3. capacitor.config.json          (read by Capacitor CLI & Android runtime)
 *   4. android/ assets (if android/ exists, runs `npx cap copy android`)
 *
 * Usage:
 *   node mobile-app/scripts/sync-config.js
 *   node mobile-app/scripts/sync-config.js https://your-school-domain.com
 *   AMS_APP_SERVER_URL=https://your-school-domain.com node mobile-app/scripts/sync-config.js
 */

const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.resolve(__dirname, "..", "..");
const CONFIG_PATH = path.join(ROOT, "mobile-app", "app-config.json");
const WWW_DIR = path.join(ROOT, "mobile-app", "www");
const CAP_CONFIG_PATH = path.join(ROOT, "capacitor.config.json");

function normalizeUrl(raw) {
  let s = String(raw || "").trim().replace(/\/+$/, "");
  if (!s) return "";
  if (!/^https?:\/\//i.test(s)) s = "https://" + s;
  const parsed = new URL(s);
  return parsed.origin + (parsed.pathname === "/" ? "" : parsed.pathname);
}

const config = JSON.parse(fs.readFileSync(CONFIG_PATH, "utf8"));

const cliUrlArg = process.argv[2] ? normalizeUrl(process.argv[2]) : "";
if (cliUrlArg) {
  config.serverUrl = cliUrlArg;
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2) + "\n", "utf8");
  console.log("[mobile-app] Saved new serverUrl in mobile-app/app-config.json:", cliUrlArg);
}

const effectiveServerUrl = process.env.AMS_APP_SERVER_URL
  ? normalizeUrl(process.env.AMS_APP_SERVER_URL)
  : normalizeUrl(config.serverUrl);

if (!effectiveServerUrl) {
  console.error("[mobile-app] Error: serverUrl cannot be empty.");
  process.exit(1);
}

const fallbackUrls = (Array.isArray(config.fallbackServerUrls) ? config.fallbackServerUrls : [])
  .map(normalizeUrl)
  .filter((u) => u && u !== effectiveServerUrl);

// 1. Copy official school logo into mobile-app/www/logo.jpg
fs.mkdirSync(WWW_DIR, { recursive: true });
const srcLogo = path.join(ROOT, "images", "LOGO.JPG");
const dstLogo = path.join(WWW_DIR, "logo.jpg");
if (fs.existsSync(srcLogo)) {
  fs.copyFileSync(srcLogo, dstLogo);
}

// 2. Write mobile-app/www/app-config.js
const runtimeConfig = {
  appId: config.appId || "com.ameenullah.school",
  appName: config.appName || "Ameenullah School",
  shortName: config.shortName || "Ameenullah",
  versionName: config.versionName || "1.0.0",
  serverUrl: effectiveServerUrl,
  fallbackServerUrls: fallbackUrls,
  themeColor: config.themeColor || "#0B2E22",
  accentColor: config.accentColor || "#EFBE4A"
};

fs.writeFileSync(
  path.join(WWW_DIR, "app-config.js"),
  "/* Auto-generated by mobile-app/scripts/sync-config.js — edit mobile-app/app-config.json instead. */\n" +
    "window.AMS_APP_CONFIG = " +
    JSON.stringify(runtimeConfig, null, 2) +
    ";\n",
  "utf8"
);

// 3. Build allowNavigation host list for Capacitor
const allowHosts = new Set([
  "*.onrender.com",
  "*.up.railway.app",
  "*.vercel.app"
]);
for (const u of [effectiveServerUrl, ...fallbackUrls]) {
  try {
    allowHosts.add(new URL(u).hostname);
  } catch (_) {}
}

const capacitorConfig = {
  appId: runtimeConfig.appId,
  appName: runtimeConfig.appName,
  webDir: "mobile-app/www",
  bundledWebRuntime: false,
  server: {
    androidScheme: "https",
    allowNavigation: Array.from(allowHosts)
  },
  android: {
    backgroundColor: runtimeConfig.themeColor,
    allowMixedContent: false
  }
};

fs.writeFileSync(CAP_CONFIG_PATH, JSON.stringify(capacitorConfig, null, 2) + "\n", "utf8");
console.log("[mobile-app] Synced capacitor.config.json -> primary server:", effectiveServerUrl);

// 4. If android/ exists, copy updated web assets & config into android/app/src/main/assets/
const androidDir = path.join(ROOT, "android");
if (fs.existsSync(androidDir) && process.env.AMS_SKIP_CAP_COPY !== "1") {
  const capBin = path.join(ROOT, "node_modules", ".bin", process.platform === "win32" ? "cap.cmd" : "cap");
  if (fs.existsSync(capBin)) {
    execFileSync(capBin, ["copy", "android"], { cwd: ROOT, stdio: "inherit" });
  }
}
